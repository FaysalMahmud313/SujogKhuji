let LANG = 'en';

function setLang(lang) {
  LANG = lang === 'bn' ? 'bn' : 'en';
  document.documentElement.lang = LANG;
}

function t(text, vars) {
  let out = LANG === 'bn' && Object.prototype.hasOwnProperty.call(I18N_BN, text) ? I18N_BN[text] : String(text ?? '');
  if (vars) out = out.replace(/\{(\w+)\}/g, (whole, name) => (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole));
  return out;
}

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    if (!el.dataset.i18n) el.dataset.i18n = el.textContent.trim();
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const name of el.dataset.i18nAttr.split(',')) {
      const slot = `i18nK${name.replace(/[^a-z]/g, '')}`;
      if (el.dataset[slot] === undefined) el.dataset[slot] = el.getAttribute(name) || '';
      el.setAttribute(name, t(el.dataset[slot]));
    }
  });
}
