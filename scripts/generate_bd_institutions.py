def main():
    seen = set()
    rows = []
    for name, extra in UNIVERSITIES:
        if name in seen:
            raise SystemExit(f"Listed twice: {name}")
        seen.add(name)
        rows.append({"name": name, "keys": extra})
    out = Path(__file__).resolve().parent.parent / "site" / "data" / "bd_institutions.json"
    out.write_text(json.dumps(rows, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {len(rows)} universities -> {out}")


if __name__ == "__main__":
    main()
